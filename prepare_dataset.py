"""
Готує датасет у структурі, яку очікує YOLOv8:

  dataset/
    images/
      train/
      val/
    labels/
      train/
      val/
    data.yaml

Запуск:
  python prepare_dataset.py img labels/labels1 dataset

Параметри:
  argv[1] — папка з .jpg
  argv[2] — папка з .txt мітками (одна на фото, з тим самим ім'ям)
  argv[3] — куди писати датасет
"""

import sys
import random
import shutil
from pathlib import Path

VAL_RATIO = 0.2   # 20% у val, 80% у train
SEED = 42         # фіксований seed для відтворюваності


def main(img_dir: str, labels_dir: str, out_dir: str):
    img_path = Path(img_dir)
    lbl_path = Path(labels_dir)
    out = Path(out_dir)

    # Зібрати пари (jpg, txt). Беремо лише фото, для яких є мітка.
    pairs = []
    for jpg in sorted(img_path.glob("*.jpg")):
        txt = lbl_path / (jpg.stem + ".txt")
        if txt.exists():
            pairs.append((jpg, txt))
        else:
            print(f"[WARN] Немає мітки для {jpg.name}")

    print(f"Знайдено {len(pairs)} пар jpg+txt")
    if not pairs:
        print("Нема з чим працювати.")
        sys.exit(1)

    # Розкидати на train/val детерміновано
    random.seed(SEED)
    random.shuffle(pairs)
    n_val = max(1, round(len(pairs) * VAL_RATIO))
    val_pairs = pairs[:n_val]
    train_pairs = pairs[n_val:]
    print(f"  train: {len(train_pairs)}")
    print(f"  val:   {len(val_pairs)}")

    # Створити структуру папок
    for split in ("train", "val"):
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)

    # Скопіювати файли
    def copy_pairs(pairs, split):
        for jpg, txt in pairs:
            shutil.copy2(jpg, out / "images" / split / jpg.name)
            shutil.copy2(txt, out / "labels" / split / txt.name)

    copy_pairs(train_pairs, "train")
    copy_pairs(val_pairs, "val")

    # data.yaml — конфіг для YOLO
    # Шляхи робимо абсолютними, бо YOLO іноді плутається у відносних
    abs_out = out.resolve()
    yaml_text = f"""# Auto-generated by prepare_dataset.py
path: {abs_out.as_posix()}
train: images/train
val: images/val

nc: 1
names: ['display']
"""
    (out / "data.yaml").write_text(yaml_text, encoding="utf-8")
    print(f"\nГотово. {out / 'data.yaml'}")
    print(f"Train: {len(train_pairs)} фото у {out / 'images' / 'train'}")
    print(f"Val:   {len(val_pairs)} фото у {out / 'images' / 'val'}")


if __name__ == "__main__":
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)
    main(sys.argv[1], sys.argv[2], sys.argv[3])