"""Dataset preparation and training for the display and digit detectors."""

import random
import shutil
from pathlib import Path

from bpocr.config import Config
from bpocr.data import discover_photos, find_images

VAL_RATIO = 0.2
SEED = 42

BASE_MODEL = "yolov8n.pt"
EPOCHS = 100
BATCH = 8
PATIENCE = 30
DISPLAY_IMG_SIZE = 640
DIGIT_IMG_SIZE = 320
DIGIT_TEMP_NAME = "_digit_detector_tmp"


def split_pairs(
    pairs: list[tuple[Path, Path]], group_of=None
) -> tuple[list[tuple[Path, Path]], list[tuple[Path, Path]]]:
    """
    Deterministic 80/20 split into (train, val). Pairs with the same group_of(pair) key
    always land on the same side; without group_of every pair is its own group.
    """
    groups: dict = {}
    for i, pair in enumerate(pairs):
        key = group_of(pair) if group_of else i
        groups.setdefault(key, []).append(pair)

    keys = list(groups)
    random.seed(SEED)
    random.shuffle(keys)
    n_val = max(1, round(len(pairs) * VAL_RATIO))
    val_pairs: list[tuple[Path, Path]] = []
    train_pairs: list[tuple[Path, Path]] = []
    for key in keys:
        (val_pairs if len(val_pairs) < n_val else train_pairs).extend(groups[key])
    return train_pairs, val_pairs


def _split_and_copy(
    pairs: list[tuple[Path, Path]], out: Path, group_of=None
) -> tuple[int, int]:
    """Deterministic 80/20 train/val split; copies images and labels into the YOLO layout."""
    train_pairs, val_pairs = split_pairs(pairs, group_of)

    for split, items in (("train", train_pairs), ("val", val_pairs)):
        (out / "images" / split).mkdir(parents=True, exist_ok=True)
        (out / "labels" / split).mkdir(parents=True, exist_ok=True)
        for img, txt in items:
            shutil.copy2(img, out / "images" / split / img.name)
            shutil.copy2(txt, out / "labels" / split / txt.name)
    return len(train_pairs), len(val_pairs)


def _pair_with_labels(images: list[Path], labels_dir: Path) -> list[tuple[Path, Path]]:
    pairs = []
    for img in images:
        txt = labels_dir / (img.stem + ".txt")
        if txt.exists():
            pairs.append((img, txt))
        else:
            print(f"[WARN] No label for {img.name}")
    return pairs


def _write_data_yaml(out: Path, script_note: str, nc: int, names: list[str]) -> Path:
    yaml_text = f"""# Auto-generated by {script_note}
path: {out.resolve().as_posix()}
train: images/train
val: images/val

nc: {nc}
names: {names!r}
"""
    path = out / "data.yaml"
    path.write_text(yaml_text, encoding="utf-8")
    return path


def prepare_display(cfg: Config, labels_dir: Path, out: Path) -> int:
    """Display dataset: original photos + their display box labels."""
    images = [p.path for p in discover_photos(cfg.photos_dir)]
    pairs = _pair_with_labels(images, labels_dir)
    print(f"Found {len(pairs)} image+label pairs")
    if not pairs:
        print("Nothing to work with.")
        return 1

    n_train, n_val = _split_and_copy(pairs, out)
    print(f"  train: {n_train}")
    print(f"  val:   {n_val}")
    data_yaml = _write_data_yaml(out, "bpocr prepare-display", 1, ["display"])
    print(f"\nDone. {data_yaml}")
    return 0


def prepare_digits(cropped_dir: Path, labels_dir: Path, out: Path) -> int:
    """Digit dataset: cropped displays + digit box labels (classes 0-9)."""
    pairs = _pair_with_labels(find_images(cropped_dir), labels_dir)
    print(f"Found {len(pairs)} image+label pairs")
    if not pairs:
        print("Nothing to work with.")
        return 1

    n_train, n_val = _split_and_copy(pairs, out)
    print(f"  train: {n_train}")
    print(f"  val:   {n_val}")

    # Class frequencies help to judge the balance
    class_count = {str(i): 0 for i in range(10)}
    for _, txt in pairs:
        with open(txt, encoding="utf-8") as f:
            for line in f:
                parts = line.strip().split()
                if parts and parts[0] in class_count:
                    class_count[parts[0]] += 1
    print("\nDigit distribution:")
    for cls in sorted(class_count, key=int):
        print(f"  {cls}: {class_count[cls]:>3}  {'#' * class_count[cls]}")

    data_yaml = _write_data_yaml(
        out, "bpocr prepare-digits", 10, [str(i) for i in range(10)]
    )
    print(f"\nDone. {data_yaml}")
    return 0


def _run_dir(model_path: Path) -> Path:
    """<runs>/detect/<name> for <runs>/detect/<name>/weights/best.pt."""
    return model_path.parent.parent


def _train(data_yaml: Path, imgsz: int, name: str, project: Path, **augment):
    from ultralytics import YOLO

    YOLO(BASE_MODEL).train(
        data=str(data_yaml),
        epochs=EPOCHS,
        imgsz=imgsz,
        batch=BATCH,
        patience=PATIENCE,
        name=name,
        project=str(project),
        device="cpu",
        **augment,
    )


def train_display(cfg: Config, data_yaml: Path) -> None:
    """Moves the previous latest run to <name>_bak, then trains a new one."""
    run = _run_dir(cfg.display_model)
    bak = run.with_name(f"{run.name}_bak")
    if run.exists():
        if bak.exists():
            shutil.rmtree(bak)
        run.rename(bak)
        print(f"Previous model moved to: {bak}")

    _train(
        data_yaml, DISPLAY_IMG_SIZE, run.name, run.parent,
        hsv_h=0.1, hsv_s=0.9, hsv_v=0.9, bgr=0.5,
        degrees=10, translate=0.1, scale=0.3,
        flipud=0.0, fliplr=0.0, mosaic=0.5,
    )
    print(f"\nDone. Active model: {cfg.display_model}")


def train_digits(cfg: Config, data_yaml: Path) -> None:
    """Trains into a temp run, then rotates: latest -> bak, temp -> latest."""
    latest = _run_dir(cfg.digit_model)
    runs_dir = latest.parent
    bak = runs_dir / (latest.name.removesuffix("_latest") + "_bak")
    tmp = runs_dir / DIGIT_TEMP_NAME

    if tmp.exists():
        shutil.rmtree(tmp)

    _train(
        data_yaml, DIGIT_IMG_SIZE, DIGIT_TEMP_NAME, runs_dir,
        flipud=0.0, fliplr=0.0, degrees=0.0, translate=0.05, scale=0.1,
        hsv_h=0.1, hsv_s=0.9, hsv_v=0.9, bgr=0.5, mosaic=0.5,
    )

    if not tmp.exists():
        print(f"Temp run {tmp} was not created - training produced no result.")
        return
    if bak.exists():
        print(f"Removing old {bak}")
        shutil.rmtree(bak)
    if latest.exists():
        print(f"Renaming {latest} -> {bak}")
        latest.rename(bak)
    print(f"Renaming {tmp} -> {latest}")
    tmp.rename(latest)

    print(f"\nDone. Active model: {cfg.digit_model}")
    print(f"Previous version: {bak / 'weights' / 'best.pt'}")
